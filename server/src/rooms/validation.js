import crypto from 'node:crypto';

// Room codes avoid look-alike characters (0/O, 1/I/L).
const CODE_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
export const CODE_LENGTH = 5;

export function generateCode() {
  const bytes = crypto.randomBytes(CODE_LENGTH);
  let code = '';
  for (let i = 0; i < CODE_LENGTH; i++) code += CODE_ALPHABET[bytes[i] % CODE_ALPHABET.length];
  return code;
}

export function normalizeCode(raw) {
  return String(raw ?? '')
    .trim()
    .toUpperCase()
    .replace(/[^A-Z0-9]/g, '');
}

export function isValidCode(code) {
  return /^[A-Z0-9]{5,6}$/.test(code);
}

export function validateNickname(raw) {
  const value = String(raw ?? '')
    .replace(/\s+/g, ' ')
    .trim();
  if (value.length < 2 || value.length > 16) return { error: 'Nickname must be 2–16 characters.' };
  if (!/^[\p{L}\p{N}\p{M} _.'-]+$/u.test(value)) {
    return { error: "Nickname can only use letters, numbers, spaces and _ . - '" };
  }
  return { value };
}

/** Guest tokens are random strings generated by the browser and kept in localStorage. */
export function validateToken(raw) {
  const s = String(raw ?? '');
  return /^[A-Za-z0-9_-]{16,64}$/.test(s) ? s : null;
}

export function newId() {
  return crypto.randomBytes(6).toString('base64url');
}
